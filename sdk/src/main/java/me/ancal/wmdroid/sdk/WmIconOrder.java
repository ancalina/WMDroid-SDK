    private WmIconOrder(){}
    static int compareForInsert(String existing,String incoming){
        int limit=Math.min(260,incoming.length());
        for(int i=0;i<limit;i++){
            int a=lower(i<existing.length()?existing.charAt(i):0),b=lower(incoming.charAt(i));
            if(a!=b||a==0)return a-b;
        }
        return 0;
    }
    private static int lower(int value){
        int lo=0,hi=RANGES.length/3;
        while(lo<hi){int mid=(lo+hi)>>>1,index=mid*3;
            if(value<RANGES[index])hi=mid;
            else if(value>RANGES[index+1])lo=mid+1;
            else return (value+RANGES[index+2])&0xffff;
        }
        return value;
    }
